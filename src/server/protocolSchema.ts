import { z } from 'zod'
import { createChannelTable, type ChannelServices } from '@host/channelTable.js'
import {
  HANDSHAKE_MAX_BYTES,
  HANDSHAKE_TIMEOUT_MS,
  authSchema,
  helloSchema,
  pairSchema
} from '@host/remoteAccess/handshake.js'
import { PROTOCOL_VERSION } from './hub.js'
import { MAX_FRAME_BYTES } from './wsListener.js'

/**
 * The contract a client of the network listener (the Flutter app) is written against, generated
 * from the zod schemas the host checks arguments with. `docs/protocol/styr-remote.schema.json` is
 * its checked-in copy; `protocolSchema.test.ts` fails when the two differ.
 */

const toSchema = (schema: z.ZodType): unknown =>
  z.toJSONSchema(schema, { unrepresentable: 'any', io: 'input', target: 'draft-2020-12' })

/** The table's schemas only: building it runs no service, so any stand-in will do. */
function standInServices(): ChannelServices {
  const nothing = new Proxy({}, { get: () => () => undefined })
  return Object.fromEntries(
    [
      'sources',
      'tasksService',
      'gitService',
      'agentsService',
      'worklogService',
      'reviewService',
      'dispatchService',
      'settingsService',
      'workspacesService',
      'cli',
      'mcpSetup',
      'usage',
      'terminals',
      'diagnostics'
    ].map((key) => [key, nothing])
  ) as unknown as ChannelServices
}

const size = z.number().int().min(1).max(10_000)

/** What the hub answers itself, beside the table (`hub.ts`). */
const HUB_CHANNELS: Record<string, { kind: 'invoke' | 'send'; params: z.ZodType; result: string }> =
  {
    'server:info': { kind: 'invoke', params: z.tuple([]), result: 'ServerInfo' },
    'server:tray': {
      kind: 'invoke',
      params: z.tuple([]),
      result: '{ statuses, titles } (shared workspaces only)'
    },
    'terminal:attach': {
      kind: 'invoke',
      params: z.tuple([z.string().min(1), size.optional(), size.optional()]),
      result: 'TerminalOutput: the backlog; live output then arrives as terminal:data'
    },
    'terminal:detach': { kind: 'invoke', params: z.tuple([z.string().min(1)]), result: 'null' },
    'terminal:focus': { kind: 'send', params: z.tuple([z.string().min(1)]), result: '' },
    'terminal:resize': {
      kind: 'send',
      params: z.tuple([z.string().min(1), size, size]),
      result: ''
    }
  }

/** Notifications the host pushes, with the shape of `params[0]`. */
const BROADCASTS: Record<string, string> = {
  'server:hello': 'ServerInfo, once after the handshake',
  'tasks:changed': 'none: re-read tasks:list',
  'agents:changed': 'none: re-read agents:list',
  'review:changed': 'the task id whose review changed',
  'sources:state': 'SourceSyncState[]',
  'orchestrate:autoState': 'AutoDispatchState',
  'orchestrate:autoStarted': 'the session Auto-run started',
  'usage:claude': 'ProviderUsage',
  'usage:context': 'ContextUsage',
  'agent:conversation': 'AgentConversation',
  'tasks:activate': 'a task id the desktop wants shown',
  'settings:changed':
    'Settings of the active workspace; { remoteAccess: false } alone when it stopped being shared with remote devices',
  'workspaces:changed': 'WorkspaceOverview, shared workspaces only',
  'workspaces:activity': 'WorkspacesActivity, shared workspaces only',
  'terminal:data': '{ id, data, sequence, marks }, only for terminals the client attached to',
  'terminal:runtimeState': 'TerminalRuntimeState',
  'terminal:exit': '{ id, exitCode }',
  'server:tray': '{ statuses, titles }, shared workspaces only'
}

export function buildProtocolSchema(): unknown {
  const { invoke, send } = createChannelTable(standInServices())
  const channels: Record<string, unknown> = {}
  for (const [name, channel] of Object.entries(invoke)) {
    channels[name] = { kind: 'invoke', params: toSchema(channel.args) }
  }
  for (const [name, channel] of Object.entries(send)) {
    channels[name] = { kind: 'send', params: toSchema(channel.args) }
  }
  for (const [name, channel] of Object.entries(HUB_CHANNELS)) {
    channels[name] = {
      kind: channel.kind,
      params: toSchema(channel.params),
      result: channel.result
    }
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'Styr remote protocol',
    description:
      'Generated by src/server/protocolSchema.ts; do not edit. See docs/architecture/remote-access.md.',
    protocol: PROTOCOL_VERSION,
    transport: {
      url: 'ws://<host>:<port>/',
      frames: 'text frames only, one JSON-RPC 2.0 message per frame',
      handshakeMaxBytes: HANDSHAKE_MAX_BYTES,
      handshakeTimeoutMs: HANDSHAKE_TIMEOUT_MS,
      maxFrameBytes: MAX_FRAME_BYTES,
      closeCodes: {
        '4400': 'bad request (binary frame)',
        '4401': 'unauthorized (every handshake failure)',
        '4403': 'the device was revoked',
        '4408': 'handshake timeout',
        '4429': 'too many attempts'
      },
      jsonRpcErrors: { '-32001': 'forbidden: the call is not open to remote devices' }
    },
    handshake: {
      hello: toSchema(helloSchema),
      auth: toSchema(authSchema),
      pair: toSchema(pairSchema)
    },
    channels,
    broadcasts: BROADCASTS
  }
}
